/**
 * 崇祯朝改革方案浏览数据
 *
 * 基于《崇祯朝改革方案总览》文档与 chapters.ts 的史实篇章，整理12项可能改革的详细信息，用于改革方案浏览页面。
 * 每个改革拆分为多张卡片（步骤卡 + 挑战卡），支持左右滑动浏览。
 */

export type ReformCardKind = 'step' | 'challenge'

export interface ReformCard {
  /** 卡片ID */
  id: string
  /** 卡片类型 */
  kind: ReformCardKind
  /** 卡片标题 */
  title: string
  /** 卡片正文 */
  body: string
  /** 财力耗费（仅步骤卡） */
  costGold?: number
  /** 人力需求（仅步骤卡） */
  costManpower?: number
  /** 所需时间（仅步骤卡，年） */
  duration?: number
  /** 基础成功率（仅步骤卡，0-100） */
  successRate?: number
  /** 提升成功率的条件（仅步骤卡） */
  boostConditions?: string[]
  /** 实施人员要求（仅步骤卡） */
  requiredRoles?: string[]
  /** 危机严重程度（仅挑战卡，1-3） */
  severity?: number
  /** 应对选项A（仅挑战卡） */
  optionA?: { label: string; effect: string }
  /** 应对选项B（仅挑战卡） */
  optionB?: { label: string; effect: string }
}

export interface Reform {
  /** 改革ID */
  id: string
  /** 改革名称 */
  name: string
  /** 改革类别 */
  category: '财政' | '军事' | '人事' | '农业' | '工业' | '监察'
  /** 可能的发生时间 */
  possibleYears: string
  /** 历史提出人 */
  proposers: string[]
  /** 总持续时间（年） */
  totalDuration: number
  /** 改革内容概述 */
  summary: string
  /** 卡片序列（步骤卡 + 挑战卡） */
  cards: ReformCard[]
  /** 前置条件 */
  prerequisites: string[]
  /** 预期收益 */
  expectedBenefits: string
}

